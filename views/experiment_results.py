import pandas as pd
import streamlit as st

from shared.data import load_experiment_results
from shared.styling import insight_card, page_header, takeaway



def render():
    page_header(
        title="Does Advertising Actually Increase Conversions?",
        subtitle=(
            "Analyzing a real randomized experiment to measure "
            "whether advertising targeting leads to more conversions."
        ),
        eyebrow="Experiment results · Criteo",
    )

    results = load_experiment_results()
    overall = results.loc[results["segment"] == "Overall"].iloc[0]

    control_rate = float(overall["control_conversion_pct"])
    treatment_rate = float(overall["treatment_conversion_pct"])
    lift = float(overall["lift_pp"])

    relative_lift = (
        lift / control_rate * 100 if control_rate else None
    )



    st.subheader("🔎 Did advertising make a difference?")

    left, right = st.columns(2)

    with left:
        st.metric(
            "Control conversion rate",
            f"{control_rate:.3f}%"
        )
    
    with right:
        st.metric(
            "Treatment conversion rate",
            f"{treatment_rate:.3f}%"
        )
    
    st.markdown(
        f"**Result: {relative_lift:+.1f}% higher conversion rate** "
        "among users eligible for advertising, equivalent to "
        f"approximately {lift * 100:.1f} additional conversions "
        "per 10,000 users."
    )




    st.subheader("⚒️ How was the experiment conducted?")
    
    st.write(
        "We analyzed 1 million users from Criteo's randomized "
        "advertising experiments to determine whether advertising "
        "increases conversions. Users were randomly assigned "
        "to two groups:"
    )
    
    left, right = st.columns(2)
    
    with left:
        insight_card(
            "Control Group · 149,825 Users",
            "No advertising targeting",
            "These users were excluded from advertising "
            "targeting, providing a baseline for comparison.",
            height=170,
        )

    with right:
        insight_card(
            "Treatment Group · 850,175 Users",
            "Eligible for advertising",
            "These users were eligible to receive ads, "
            "allowing us to measure whether advertising "
            "increased conversions.",
            height=170,
        )

    
    st.caption(
        "Not all users eligible for advertising necessarily saw an ad. "
        "This analysis is separate from the proposed GA4 product-page experiment."
    )


    results = load_experiment_results()
    overall = results.loc[results["segment"] == "Overall"].iloc[0]
    control_rate = float(overall["control_conversion_pct"])
    treatment_rate = float(overall["treatment_conversion_pct"])
    lift = float(overall["lift_pp"])
    lower = float(overall["ci_lower_pp"])
    upper = float(overall["ci_upper_pp"])
    relative_lift = lift / control_rate * 100 if control_rate else None

    
    st.subheader("🔎 Did advertising make a difference?")
    
    col1, col2 = st.columns(2)
    
    with col1:
        st.metric(
            "Control conversion rate",
            f"{control_rate:.3f}%"
        )
        st.caption("281 of 149,825 users converted.")
    
    with col2:
        st.metric(
            "Treatment conversion rate",
            f"{treatment_rate:.3f}%"
        )
        st.caption("2,540 of 850,175 users converted.")
    
    st.metric(
        "Increase in conversion rate",
        f"{relative_lift:+.1f}%"
    )
    
    st.write(
        "**Users eligible for advertising had a 59.3% higher "
        "conversion rate** than users excluded from targeting."
    )


    st.subheader(" 💡 What is the decision?")

    st.write("**Is the effect large enough to matter to the business?**")

    incremental = lift * 1_000
    incremental_lower = lower * 1_000
    incremental_upper = upper * 1_000

    st.write(
        f"The estimated lift translates to **{incremental:.1f} incremental "
        f"conversions per 100,000 users assigned to treatment** "
        f"(95% CI: {incremental_lower:.1f}–{incremental_upper:.1f}). "
    )

    st.markdown(
        "- **Practical significance:** The effect could matter at scale, "
        "but its value depends on campaign reach and the contribution "
        "margin generated by each incremental conversion.\n"
        "- **Profitability:** Incremental contribution must exceed "
        "incremental advertising and campaign costs.\n"
        "- **Guardrails:** Confirm that customer experience, "
        "unsubscribe rates, and other relevant outcomes remain acceptable."
    )

    st.caption(
        "Incremental profit = incremental conversions × contribution "
        "margin per conversion − incremental campaign cost."
    )

    takeaway(
        "Recommendation: validate the effect in a production experiment. "
        "Scale if the incremental profit meets the business return "
        "threshold and guardrail metrics remain acceptable. Statistical "
        "significance alone is insufficient to justify rollout."
    )

    st.write(
        "**Next question:** Can uplift modeling identify users with a "
        "larger incremental response and improve targeting efficiency?"
    )

    with st.expander("Statistical methodology"):
        st.markdown(
            "- **Treatment effect:** Intention-to-treat difference in user conversion rates; "
            "users are compared by assignment, regardless of actual ad exposure.\n"
            "- **Null hypothesis:** Treatment and control conversion rates are equal.\n"
            "- **Test:** Two-sided two-proportion z-test, α = 0.05.\n"
            "- **95% confidence interval:** Normal approximation \n"
            "- **Group sizes:** The comparison accounts for each group's "
            "conversion rate and sample size."
        )

    st.markdown(
        "[Criteo dataset documentation]"
        "(https://huggingface.co/datasets/criteo/criteo-uplift)"
    )
